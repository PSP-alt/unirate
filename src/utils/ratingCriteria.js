/* Объединяющая утилита: для multi-type преподавателей берёт
   уникальные критерии из ВСЕХ его типов (по ключу). Для одного
   типа возвращает его критерии. Если ничего нет — universal.
   Раньше при выборе [lecturer, seminar] клиент молча сваливался
   на 'universal', теряя специфику. */
export function getCriteriaForTeacher(teacher) {
  if (!teacher) return RATING_CRITERIA.universal
  const types = teacher.teacherTypes?.length
    ? teacher.teacherTypes
    : [teacher.teacherType || 'universal']
  const seen = new Set()
  const result = []
  for (const type of types) {
    const list = RATING_CRITERIA[type] || []
    for (const crit of list) {
      if (!seen.has(crit.key)) {
        seen.add(crit.key)
        result.push(crit)
      }
    }
  }
  return result.length ? result : RATING_CRITERIA.universal
}
